"""Regenerate game/data/cleanpylons.py: the stations where DCS can remove the pylon.

DCS offers ``<CLEAN>`` (take the pylon off) only on some stations. pydcs's export
cannot map that store, so it survives only as an ``# ERRR <CLEAN>`` comment after
the station's ``PylonN`` class. The built app has no .py sources to read, so the
table is generated here and checked into the tree.

    python tools/clean_pylons.py          # print the table
    python tools/clean_pylons.py --write  # rewrite game/data/cleanpylons.py
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Iterable

import dcs

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "game" / "data" / "cleanpylons.py"

_AIRCRAFT = re.compile(r"^class \w+\((?:PlaneType|HelicopterType)\):")
_OTHER_CLASS = re.compile(r"^class ")
_UNIT_ID = re.compile(r'^    id = "([^"]+)"')
_PYLON = re.compile(r"^    class Pylon(\d+):")
_CLEAN = re.compile(r"^\s*# ?ERRR <CLEAN>\s*$")


def source_files() -> list[Path]:
    pydcs = Path(dcs.__file__).parent
    files = [pydcs / "planes.py", pydcs / "helicopters.py"]
    files.extend(sorted((ROOT / "pydcs_extensions").rglob("*.py")))
    return files


def scan_lines(lines: Iterable[str]) -> dict[str, set[int]]:
    found: dict[str, set[int]] = {}
    unit_id: str | None = None
    pylon: int | None = None
    in_aircraft = False
    for line in lines:
        if _AIRCRAFT.match(line):
            in_aircraft, unit_id, pylon = True, None, None
        elif _OTHER_CLASS.match(line):
            in_aircraft, unit_id, pylon = False, None, None
        elif not in_aircraft:
            continue
        elif unit_id is None and (match := _UNIT_ID.match(line)):
            unit_id = match.group(1)
        elif match := _PYLON.match(line):
            pylon = int(match.group(1))
        elif _CLEAN.match(line) and unit_id is not None and pylon is not None:
            found.setdefault(unit_id, set()).add(pylon)
    return found


def scan() -> dict[str, frozenset[int]]:
    found: dict[str, set[int]] = {}
    for path in source_files():
        lines = path.read_text(encoding="utf-8").splitlines()
        for unit_id, pylons in scan_lines(lines).items():
            found.setdefault(unit_id, set()).update(pylons)
    return {unit_id: frozenset(found[unit_id]) for unit_id in sorted(found)}


def render(table: dict[str, frozenset[int]]) -> str:
    rows = "".join(
        f"    {unit_id!r}: frozenset({{{', '.join(str(n) for n in sorted(pylons))}}}),\n"
        for unit_id, pylons in table.items()
    ).replace("'", '"')
    return (
        '"""Stations where DCS can remove the pylon (the ``<CLEAN>`` store).\n'
        "\n"
        "Generated by tools/clean_pylons.py from the pydcs export; do not edit.\n"
        '"""\n'
        "\n"
        "CLEAN_PYLONS: dict[str, frozenset[int]] = {\n"
        f"{rows}"
        "}\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help=f"rewrite {OUTPUT}")
    args = parser.parse_args()
    text = render(scan())
    if args.write:
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"Wrote {OUTPUT}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
